# second line's own truncated OCR reading, e.g. "6205-001" for a genuine
# "21-62-05-001" -- see module docstring; the anchor only needs a stable Y
# position, not a perfectly-decoded value).
_ANCHOR_RE = re.compile(r"^[\dA-Za-z]{1,4}-[\dA-Za-z-]{1,10}$")
_ATA_TOKEN_RE = re.compile(r"^\d{2}$")
