# Y-tolerance for bucketing a non-anchor column's word to its nearest
# TASK_CARD anchor -- measured directly against this file's own row pitch
# (~32.5px @ 300 DPI between consecutive rows); comfortably under half
# that, to avoid bleeding a neighbouring row's own value into this one.
_ANCHOR_TOLERANCE_PX = 14

_FILLABLE = ("PART_NUMBER", "SERIAL_NUMBER", "DESCRIPTION", "POSITION",
             "INSTALLED_DATE")

_HEADER_FIELDS = ["OPERATOR", "MSN", "REPORT_DATE", "TAH", "TAC"]

_DATE_HDR_RE = re.compile(r"Date\s+(\S+)", re.IGNORECASE)
_TAH_RE = re.compile(r"TAH\s+(\S+)", re.IGNORECASE)
_TAC_RE = re.compile(r"TAC\s+(\S+)", re.IGNORECASE)
_MSN_RE = re.compile(r"MSN\s+(\S+)", re.IGNORECASE)


def _col_bounds(w: int, name: str) -> tuple[int, int]:
    for lo, hi, col in _COLUMNS:
        if col == name:
            return int(lo * w), int(hi * w)
    raise KeyError(name)


async def _ocr_column(img, name: str, y0: int, y1: int, scale: int = 2) -> list[tuple[float, str]]:
    """OCR one column's full-height strip and return (top, text) pairs in
    original-image page coordinates."""
    x0, x1 = _col_bounds(img.width, name)
    crop = img.crop((x0, y0, x1, y1))
    if scale != 1:
        crop = crop.resize((crop.width * scale, crop.height * scale), Image.LANCZOS)
    words = await ocr_words(crop, psm=6, min_conf=-1)
    out = []
    for w in words:
        text = str(w.get("text", "")).strip()
        if not text:
            continue
        out.append((y0 + w["top"] / scale, text))
    return out


def _best_numeric(found: list[str]) -> str:
    """A ruled numeric cell holds exactly one value; multiple digit-group
    matches from one anchor's own OCR tokens are either (a) the same value
    read twice (adjacent word-boxes for one printed number) or (b) a short
    noise fragment (a stray leader-dot run OCR'd as 1-2 digits) alongside
    the real, longer reading. Deduping exact repeats and then keeping the
    longest remaining match handles both without guessing at a merge."""
    seen = list(dict.fromkeys(found))  # dedupe, preserve order
    if not seen:
        return ""
    return max(seen, key=len)


def _clean_field(name: str, tokens: list[str]) -> str:
    if name in _NUMERIC_COLS:
        found: list[str] = []
        for t in tokens:
            found.extend(_NUM_TOKEN_RE.findall(t))
        return _best_numeric(found)
    if name in _DATE_COLS:
        found = []
        for t in tokens:
            found.extend(_DATE_TOKEN_RE.findall(t))
        found = list(dict.fromkeys(found))
        return " ".join(found)
    if name in _DAY_OR_DATE_COLS:
        found = []
        for t in tokens:
            found.extend(_DATE_TOKEN_RE.findall(t))
            if not _DATE_TOKEN_RE.search(t):
                found.extend(_NUM_TOKEN_RE.findall(t))
        found = list(dict.fromkeys(found))
        if len(found) > 1:
            return _best_numeric(found)
        return " ".join(found)
    sep = " " if name in _JOIN_SPACE else ""
    text = sep.join(tokens)
    if name in _CODE_COLS:
        text = text.strip(_CODE_STRIP_CHARS)
    return text


async def _parse_header(img) -> dict:
    """Per-line crop + OCR of the Date/TAH/TAC block and the MSN/title/
    operator band -- see module docstring for why a single whole-header
    OCR pass isn't used (unreliable on some pages of the sample file)."""
    meta = {k: "" for k in _HEADER_FIELDS}
    w = img.width

    async def line(y0: int, y1: int, x0: int, x1: int, psm: int = 6) -> str:
        crop = img.crop((x0, y0, x1, y1))
        crop = crop.resize((crop.width * 3, crop.height * 3), Image.LANCZOS)
        return (await ocr_text(crop, psm=psm)).strip()

    block = await line(50, 220, 0, min(520, w))
    m = _DATE_HDR_RE.search(block)
    if m:
        meta["REPORT_DATE"] = m.group(1)
    m = _TAH_RE.search(block)
    if m:
        meta["TAH"] = m.group(1)
    m = _TAC_RE.search(block)
    if m:
        meta["TAC"] = m.group(1)

    title = await line(100, 190, int(w * 0.24), int(w * 0.62))
    m = _MSN_RE.search(title)
    if m:
        meta["MSN"] = m.group(1)

    operator = await line(30, 130, int(w * 0.62), w)
    operator = " ".join(operator.split())
    if operator:
        meta["OPERATOR"] = operator

    return meta


async def ocr_detect(pdf_path: str) -> bool:
    """Cheap page-1 OCR check for the router's blank-text fallback. Not
    expected to fire for the known source file (its baked-in text layer is
    never blank -- it's found via plain-text SIGNATURES instead, see module
    docstring), kept for interface consistency and in case a more severely
    degraded copy of this template turns up with no usable text layer at
    all."""
    try:
        img = await render_page(pdf_path, 0, dpi=300)
        w = img.width
        crop = img.crop((int(w * 0.24), 100, int(w * 0.62), 190))
        crop = crop.resize((crop.width * 2, crop.height * 2), Image.LANCZOS)
        text = (await ocr_text(crop, psm=6)).upper()
        return "HARD TIME COMPONENTS STATUS REPORT" in text
    except Exception:
        return False


async def extract(pdf_path: str) -> list[dict]:
    records: list[dict] = []
    header_meta = {k: "" for k in _HEADER_FIELDS}
    n_pages = await page_count(pdf_path)

    for page_index in range(n_pages):
        img = await render_page(pdf_path, page_index, dpi=300)
        h = img.height

        if not all(header_meta.values()):
            page_meta = await _parse_header(img)
            for k, v in page_meta.items():
                if v and not header_meta[k]:
                    header_meta[k] = v

        col_words: dict[str, list[tuple[float, str]]] = {}
        for _, _, name in _COLUMNS:
            col_words[name] = await _ocr_column(img, name, 260, h)

        anchors = sorted(
            top for top, text in col_words["TASK_CARD"]
            if _ANCHOR_RE.match(text)
        )

        cur = {f: "" for f in _FILLABLE}
        for atop in anchors:
            row: dict[str, str] = {}
            for _, _, name in _COLUMNS:
                if name == "TASK_CARD":
                    continue
                toks = [text for top, text in col_words[name]
                        if abs(top - atop) <= _ANCHOR_TOLERANCE_PX]
                row[name] = _clean_field(name, toks)

            tc_toks = [text for top, text in col_words["TASK_CARD"]
                       if abs(top - atop) <= _ANCHOR_TOLERANCE_PX]
            row["TASK_CARD"] = " ".join(tc_toks).strip(_CODE_STRIP_CHARS)

            # ATA: best-effort only, never forward-filled (see module
            # docstring).
            if not _ATA_TOKEN_RE.match(row.get("ATA", "")):
                row["ATA"] = ""

            for f in _FILLABLE:
                if row[f]:
                    cur[f] = row[f]
                else:
                    row[f] = cur[f]

            row["_page"] = page_index + 1
            row.update(header_meta)
            records.append(row)

    return records
