"""HARD TIME COMPONENTS STATUS REPORT -- scanned "sandwich" PDF (a raster
page image with an old, low-quality OCR text layer baked in underneath),
needs a fresh per-column-strip OCR pass end to end; the file's own baked-in
text layer is unusable for row data.

Confirmed directly on a real corpus file (4 pages): `page.rects`/
`page.lines`/`page.curves` are all empty on every page and `page.images`
holds exactly one full-page raster image per page -- the ruled grid visible
when the page is rendered is part of that raster image, not vector-drawn,
so `extract_tables()` returns nothing (unlike this package's other
ruled-table HT variants, e.g. `mpd_service_interval_status.py`, which read
a genuine vector-drawn grid via `extract_tables()` directly).

`page.extract_text()` is NOT blank (over 1000 characters per page, so the
router's own generic "blank text -> OCR fallback" check never fires), but
the words are badly scrambled at the character level -- e.g. "PACK BYPASS
VALVE/TRIM AIR MODUL VLV" decodes as "pacbkypavsaslve/triamirmoduvllv".
Confirmed directly this is NOT a broken font/glyph-mapping issue (unlike
`hard_time_aircraft_components_status_broken_font.py`'s own file): reading
`page.chars` directly shows every individual character decodes correctly
with a plain `Helvetica` font and correct per-character Unicode text --
only whole-word ordering/spacing is wrong. Cross-checking column
position against a clean rendered-image reading of the same file confirms
the actual page content is an old, independently-OCR'd text layer of
middling quality (baked into the PDF at some prior processing step, not
generated by pdfplumber) -- it merges adjacent words with no space,
sporadically drops or misreads individual characters (e.g. this file's own
"Partno"/"Pos."/"Inst-Date" column headers decode as "panno"/"p05."/
"inn-date"), and is therefore not trustworthy for exact PART_NUMBER/
SERIAL_NUMBER/date values even where a human reader could visually
resolve the correct value from the same misread text. So this variant
ignores that text layer entirely (it is useful only as the plain-text
SIGNATURES anchor below, where the exact phrase happens to decode cleanly)
and instead re-derives every field from a fresh render + OCR pass, per
this project's per-column-strip-OCR convention for a file whose whole-page/
whole-row OCR would otherwise be unreliable.

Header block (repeats near-identically on every page, upper-left corner)::

    Date   <report date>
    TAH    <total aircraft hours>
    TAC    <total aircraft cycles>

...and, centered/right on the same header band::

    MSN <msn> HARD TIME COMPONENTS STATUS REPORT      <operator wordmark>

Confirmed directly: a tight per-line crop (not a single whole-header OCR
pass, which mis-reads on some pages) around each of these three lines,
upscaled 2x-3x, OCRs cleanly and identically across all 4 pages of the
sample file. Parsed once per page and kept the first time every field is
non-empty (mirrors this package's usual header-metadata convention), since
a page's own header crop occasionally fails where an earlier page's
succeeded.

Main table, one ruled header row (part of the page's own raster image, not
extractable text), 20 columns::

    ATA | Partno | Serialno | Description | Pos. | Inst-Date | TASK CARD |
    TASK | INTERVAL{DAY,FHR,CYC} | LAST DONE{DAY,FHR,CYC} |
    NEXT DUE{DATE,FHR,CYC} | REMAINING{DAY,FHR,CYC}

Column X-boundaries below are expressed as fractions of the rendered page's
own width (confirmed directly via a numpy column-darkness scan for the
ruled grid's own vertical divider lines on page 1, at 300 DPI) rather than
fixed pixel offsets -- this file's own 4 pages render at two very slightly
different physical widths (831.36pt vs 829.44pt, under 0.3%), so a
fraction-of-width scheme keeps every column's own crop aligned on every
page without needing a per-page recalibration pass.

Row anchoring: TASK_CARD is used as the per-row Y anchor (a short
digit-and-dash token, e.g. "21-51-10-001", present on very nearly every
real data row -- including a component's own second/third scheduled-task
row, which repeats PART_NUMBER/SERIAL_NUMBER/DESCRIPTION/POSITION/
INSTALLED_DATE as blank cells but always carries its own TASK_CARD and
TASK). This is a deliberately different anchor choice than this package's
other per-column-strip HT variant (`hard_time_aircraft_components_status_
broken_font.py`'s own ATA-column anchor) -- confirmed directly on this
file's own sample that the ATA column is far too sparse (it holds a bare
chapter code only on the first row of a new ATA chapter, blank on every
other row) and, worse, unreliable even where present: a single whole-column
OCR pass drops or mis-segments an isolated 2-digit code surrounded by nine
blank rows above and below it in a way a dense, virtually-every-row column
like TASK_CARD does not suffer from. Rather than guess at a fix for that
column's own OCR reliability, ATA is captured on a best-effort basis only
(whatever a bare whole-column OCR pass finds, filtered to a plausible
chapter-code range) and is NOT forward-filled from the previous row --
unlike PART_NUMBER/SERIAL_NUMBER/DESCRIPTION/POSITION/INSTALLED_DATE below,
which anchor reliably enough to forward-fill with confidence, a
best-effort-only ATA reading that turned out wrong would silently
mis-attribute an entire chapter's worth of rows to the wrong ATA if forward-
filled; left blank-or-detected instead, this is a visibly incomplete field
rather than a confidently wrong one (`sheet_types/ht.py`'s own
`normalize_and_validate()` does not call `shared.cleanup.forward_fill_ata`
the way `occm.py` does, so this is a deliberate per-variant choice, not a
gap the router papers over).

Row grain: a tracked component instance is usually one physical row, but
PART_NUMBER/SERIAL_NUMBER/DESCRIPTION/POSITION/INSTALLED_DATE come back
blank on a second (or third) row directly below when that row is a second
scheduled task under the very same physical unit (same PN/SN, a new
TASK_CARD of its own, e.g. a battery's own "PARTIAL OVERHAUL" line and its
own sibling "OVERHAUL, OR PERFORM ALL RELEVANT CMM" line). These are
reconstructed with a single forward-fill pass, independently per field,
NOT reset per page (confirmed directly on the sample file: unlike
`mpd_service_interval_status.py`'s own file, this file's own chapter/
component runs do cross a page boundary without repeating the PN/SN/
description on the new page's own first row).

Numeric/date cells (INTERVAL/LAST DONE/NEXT DUE/REMAINING) sit behind the
same dotted leader-line styling used throughout this ruled grid; a
column's own OCR pass frequently picks up the leader dots and stray ruled-
border pixels as junk tokens (e.g. ":", "|", ";", or a short garbled run).
Rather than pass these through or try to character-map-correct them, each
of these columns is reduced to only its own digit-and-punctuation
substrings (a plain `\d[\d,]+` scan across the column's raw OCR tokens,
`\d{1,2}[.\-]\d{1,2}[.\-]\d{2,4}` for the one date-shaped column) and
non-numeric noise is dropped outright -- per this project's "never guess a
wrong split" convention, a dropped stray artifact is preferred over a
confidently-wrong merged value. LAST_DONE_DAY is a partial exception: this
file's own real rows put either a bare day-count integer OR a full
calendar date in that same ruled cell (confirmed directly, e.g. a battery's
"PARTIAL OVERHAUL" row leaves it blank while its own sibling "OVERHAUL, OR
PERFORM ALL RELEVANT CMM" row on the very same physical component carries a
real date there) -- so this column accepts either shape rather than forcing
one.
"""
